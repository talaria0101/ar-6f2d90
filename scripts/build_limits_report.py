#!/usr/bin/env python3
"""Generate report/03-limits.md from the two limit sources.

Usage: python3 scripts/build_limits_report.py

Sources:
  data/limits.tsv          sentences found by the regex extractor over the
                           captured terms pages
  data/limits_curated.tsv  sentences read out of a capture by hand, each with
                           its exact quote, verified by scripts/check_limits.py

The report prints both, marks which is which, and names every provider whose
capture yielded no limit sentence. A provider with no sentence is not a
provider with no limit; the capture may not contain one, or the limit may sit
in a table the extractor cannot read.
"""
import csv
from collections import defaultdict


def load(path):
    with open(path, encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def main():
    auto = load("data/limits.tsv")
    curated = load("data/limits_curated.tsv")
    providers = [r["provider"] for r in auto]

    curated_by = {r["provider"]: r for r in curated}
    auto_by = {r["provider"]: r for r in auto}

    lines = []
    lines.append("# Documented rate limits and authentication requirements")
    lines.append("")
    lines.append("Generated by `scripts/build_limits_report.py`. Every quote here "
                 "is present in the captured page named beside it; "
                 "`scripts/check_limits.py` re-verifies the curated ones, and "
                 "`scripts/capture_terms.py` produced the extracted ones from the "
                 "same captures.")
    lines.append("")
    lines.append("A limit is a property of a provider at capture time. Providers "
                 "change them, and a limit that is absent from this file is a limit "
                 "that was not found in the captured page, not a limit that does "
                 "not exist.")
    lines.append("")

    lines.append("## Limits read from the capture (verified quote)")
    lines.append("")
    lines.append("| provider | limit | unit | quote | capture |")
    lines.append("|---|---|---|---|---|")
    for r in curated:
        lines.append("| %s | `%s` | %s | \"%s\" | `%s` |" % (
            r["provider"], r["limit_quote"][:120].replace("|", "%7C"),
            r["unit"], r["limit_quote"][:200].replace("|", "%7C"),
            r["capture_path"]))
    lines.append("")

    # Auto-extracted rows that add a provider the curated list does not cover.
    extra = [r for r in auto if r["limit_sentence"] != "not-found"
             and r["provider"] not in curated_by]
    lines.append("## Limits found by the pattern extractor only")
    lines.append("")
    if extra:
        lines.append("| provider | sentence | capture |")
        lines.append("|---|---|---|")
        for r in extra:
            lines.append("| %s | \"%s\" | `%s` |" % (
                r["provider"], r["limit_sentence"].replace("|", "%7C"),
                r["capture_path"]))
    else:
        lines.append("None. Every sentence the extractor found is either in the "
                     "verified table above or was a page heading rather than a "
                     "limit.")
    lines.append("")

    missing = [r["provider"] for r in auto if r["limit_sentence"] == "not-found"
               and r["provider"] not in curated_by]
    lines.append("## Providers with no limit sentence in the capture (%d)" % len(missing))
    lines.append("")
    lines.append("These pages were fetched and read. No sentence in them stated a "
                 "request ceiling in a shape the extractor recognises, and none "
                 "was promoted by hand. The capture is named so a reader can look.")
    lines.append("")
    lines.append("| provider | HTTP | capture |")
    lines.append("|---|---|---|")
    for r in auto:
        if r["provider"] in missing:
            lines.append("| %s | %s | `%s` |" % (r["provider"], r["code"],
                                                 r["capture_path"]))
    lines.append("")

    lines.append("## What this does not establish")
    lines.append("")
    lines.append("- A quoted limit is what the page said, not what the server "
                 "enforces. No rate limit in this file was exercised by exceeding "
                 "it.")
    lines.append("- The absence of a quote for a provider says nothing about that "
                 "provider's actual limits.")
    lines.append("- Nothing here is a statement about whether a given use is "
                 "permitted by a provider's terms. This is a technical inventory.")
    lines.append("")

    with open("report/03-limits.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("report/03-limits.md: %d verified quotes, %d extractor-only, "
          "%d providers without a sentence" % (len(curated), len(extra), len(missing)))


if __name__ == "__main__":
    main()
