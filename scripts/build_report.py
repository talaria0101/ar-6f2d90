#!/usr/bin/env python3
"""Generate report/01-providers.md from data/providers.tsv.

Usage: python3 scripts/build_report.py

The table is generated, never hand-edited, so a figure in the report cannot
drift from the figure in the TSV. Every row carries the observed fact and the
artefact path; the artefact path is what check_reports.py verifies.
"""
import csv
import os
from collections import Counter, defaultdict


def load():
    with open("data/providers.tsv", encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def main():
    rows = load()
    rows.sort(key=lambda r: (r["category"], r["provider"].lower(), r["service"]))

    providers = defaultdict(list)
    for r in rows:
        providers[r["provider"]].append(r)

    lines = []
    lines.append("# Providers with a working public API: academic and archival services")
    lines.append("")
    lines.append("Generated by `scripts/build_report.py` from `data/providers.tsv`. "
                 "Every row names the captured response that proves it. "
                 "Run `python3 scripts/check_reports.py` to re-verify all of them.")
    lines.append("")
    lines.append("## What the columns mean")
    lines.append("")
    lines.append("| column | meaning |")
    lines.append("|---|---|")
    lines.append("| `provider` | the organisation that operates the API. Several "
                 "endpoints from one provider are listed separately. |")
    lines.append("| `service` | the specific endpoint set. |")
    lines.append("| `auth` | what the anonymous probe needed. `none` answered with "
                 "no credential at all; `key-optional` answered anonymously and "
                 "also documents a keyed mode with a higher allowance; "
                 "`demo-key` answered only when the published demo key that "
                 "appears in the vendor's own documentation was supplied; "
                 "`email-required` wants a contact address in the query. Every "
                 "`demo-key` row was also probed with no credential at all and "
                 "refused, so the key is load-bearing, not decorative. "
                 "`key-required` means the anonymous probe returned a refusal; "
                 "no `key-required` row is in this table. |")
    lines.append("| `observed` | one fact read out of the captured body: a result "
                 "count, a row count, an identifier, or the document shape. |")
    lines.append("| `bytes` / `sha256` | size and digest of the captured body. |")
    lines.append("| `evidence_path` | the captured body itself. |")
    lines.append("")
    lines.append("The `observed` figure is not a vendor claim. It is the number the "
                 "service returned to a single unauthenticated request made from "
                 "this sandbox on 2026-10-20, with the query shown in the probe URL. "
                 "A different query returns a different number; the figure proves the "
                 "endpoint answered, not that the corpus is that size.")
    lines.append("")

    # Summary.
    n_providers = len(providers)
    n_endpoints = len(rows)
    cats = Counter(r["category"] for r in rows)
    auths = Counter(r["auth"] for r in rows)
    lines.append("## Summary")
    lines.append("")
    lines.append("| measure | value |")
    lines.append("|---|---|")
    lines.append("| distinct providers | %d |" % n_providers)
    lines.append("| distinct endpoints | %d |" % n_endpoints)
    lines.append("| academic | %d endpoints |" % cats.get("academic", 0))
    lines.append("| archive | %d endpoints |" % cats.get("archive", 0))
    for k in sorted(auths):
        lines.append("| auth `%s` | %d endpoints |" % (k, auths[k]))
    lines.append("| distinct hosts probed | %d |" % len({r["host"] for r in rows}))
    lines.append("")

    # The table, grouped by provider.
    lines.append("## Endpoints")
    lines.append("")
    lines.append("| # | service | provider | cat | auth | observed | bytes | evidence |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(rows, 1):
        lines.append("| %d | %s | %s | %s | %s | `%s` | %s | `%s` |" % (
            i, r["service"], r["provider"], r["category"], r["auth"],
            r["observed"], r["bytes"], r["evidence_path"]))
    lines.append("")

    os.makedirs("report", exist_ok=True)
    with open("report/01-providers.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("report/01-providers.md: %d endpoints, %d providers" % (n_endpoints, n_providers))


if __name__ == "__main__":
    main()
