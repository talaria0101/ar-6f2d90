#!/usr/bin/env python3
"""Generate report/02-exclusions.md: every probed URL that is not in the table.

Usage: python3 scripts/build_exclusions.py

The table in report/01 lists what answered. This file lists what did not,
grouped by the verdict from scripts/classify_probes.py, with the captured body
named. An excluded service is not a claim that it has no API; it is a claim
that this probe, from this sandbox, did not get a payload. Each group says what
would change the verdict.
"""
import csv
import re
import os
from collections import defaultdict

EXPLAIN = {
    "challenge": (
        "The host served a bot interstitial instead of the API. This is a "
        "property of the request, not of the service: the same URL is expected "
        "to answer from a browser or from an IP the host has not flagged. A "
        "verdict here is `unproven from this sandbox`, not `no API`."),
    "auth": (
        "The service answered and refused for want of a credential. The "
        "endpoint exists; the anonymous allowance is zero. Each of these is a "
        "candidate for a keyed probe, which this pass did not make."),
    "error": (
        "The URL returned 404, 410 or 5xx. In most of these the path was wrong "
        "rather than the service absent; the endpoint that does work may be a "
        "different path on the same host."),
    "empty": (
        "The host answered 202 or 200 with no body. A 202 is a challenge in "
        "progress; an empty 200 is a placeholder."),
    "unreachable": (
        "No response at all: DNS, TLS or proxy failure. Several of these hosts "
        "are plain HTTP-only or refuse the sandbox's egress."),
    "throttled": (
        "The service refused on volume. The endpoint works; the probe arrived "
        "inside a rate window that was already exhausted."),
    "banner": (
        "The service returned a version banner rather than a result. The host "
        "is up; the path probed is an API root, not a search endpoint."),
    "alternate-of-listed": (
        "A payload from an endpoint already in the table, captured again with a "
        "different parameter set or in a different wave. It is listed here so "
        "that every probe is accounted for; it is not an exclusion."),
    "payload-not-listed": (
        "A payload from an endpoint the table does not list. These are the "
        "services this pass reached but did not promote to a row."),
    "html": (
        "The host returned an HTML page that is neither a challenge nor an "
        "API document. These were site pages, not endpoints."),
}


def load(path):
    with open(path, encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def main():
    verdicts = load("evidence/verdicts.tsv")
    in_table_rows = load("data/providers.tsv")
    in_table = {r["probe_slug"] for r in in_table_rows}

    # The same URL was probed in more than one wave. Collapse by URL first so
    # the counts are counts of endpoints, not of attempts; the per-attempt rows
    # stay in evidence/verdicts.tsv.
    by_url = {}
    for v in verdicts:
        key = v["url"].strip()
        if key not in by_url:
            by_url[key] = v
        elif by_url[key]["verdict"] == "payload" and v["verdict"] != "payload":
            # Keep a non-payload verdict if any attempt produced one; that is
            # the more informative reading of the endpoint.
            by_url[key] = v

    def norm(u):
        from urllib.parse import urlsplit
        p = urlsplit(u)
        return (p.hostname or "") + re.sub(r"/+$", "", p.path).lower()

    listed_keys = {norm(r["probe_url"]) for r in in_table_rows}

    groups = defaultdict(list)
    for v in by_url.values():
        if v["slug"] in in_table:
            continue
        if v["verdict"] == "payload":
            # A payload whose host+path matches a listed row is an alternate
            # capture of an endpoint already in the table, not an exclusion.
            # A payload with no matching path is an endpoint the table missed.
            if norm(v["url"]) in listed_keys:
                groups["alternate-of-listed"].append(v)
            else:
                groups["payload-not-listed"].append(v)
            continue
        groups[v["verdict"]].append(v)

    lines = []
    lines.append("# Probes that did not produce a table row")
    lines.append("")
    lines.append("Generated by `scripts/build_exclusions.py` from "
                 "`evidence/verdicts.tsv`. Every URL this pass probed appears "
                 "either in `report/01-providers.md` or here.")
    lines.append("")
    lines.append("An exclusion is a statement about one request from one "
                 "sandbox at one moment. It is not a statement that the service "
                 "has no API.")
    lines.append("")

    order = ["auth", "challenge", "throttled", "empty", "banner", "error",
             "html", "unreachable", "payload-not-listed", "alternate-of-listed"]
    for kind in order:
        rows = groups.get(kind, [])
        if not rows:
            continue
        rows.sort(key=lambda r: r["slug"])
        lines.append("## %s (%d)" % (kind, len(rows)))
        lines.append("")
        if kind in EXPLAIN:
            lines.append(EXPLAIN[kind])
            lines.append("")
        lines.append("| slug | HTTP | bytes | reason | URL | captured body |")
        lines.append("|---|---|---|---|---|---|")
        for r in rows:
            lines.append("| %s | %s | %s | %s | `%s` | `%s` |" % (
                r["slug"], r["code"], r["bytes"], r["reason"],
                r["url"].replace("|", "%7C"), r["path"]))
        lines.append("")

    with open("report/02-exclusions.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    total = sum(len(v) for v in groups.values())
    print("report/02-exclusions.md: %d excluded probes across %d verdicts"
          % (total, len(groups)))
    for kind in order:
        if groups.get(kind):
            print("  %-20s %d" % (kind, len(groups[kind])))


if __name__ == "__main__":
    main()
